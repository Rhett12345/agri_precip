# 日期格式校验
def _validate_dates(dates: list[str], name: str) -> None:
    for d in dates:
        try:
            datetime.strptime(d, "%Y%m%d")
        except ValueError:
            raise ValueError(f"{name} 中日期格式无效: {d} (期望 YYYYMMDD)")

